type MessageRole = 'user' | 'agent' | 'system';

/** Content blocks inside a persisted/streaming agent turn. */
export type AgentBlock =
  | { type: 'text'; text: string }
  | { type: 'thinking'; text: string }
  | {
      type: 'tool';
      id: string;
      name: string;
      input: unknown;
      result?: { ok: boolean; summary: string };
    }
  // A resolved `maestro-ask` prompt, folded back into the turn so the question
  // and the user's answer stay visible in the trace after the picker is gone.
  // `answers` is null when the user dismissed the prompt (or the run was stopped).
  | {
      type: 'ask';
      questions: AskQuestion[];
      answers: AskAnswer[] | null;
    };

