/** The delegation preamble appended to the orchestrator's system prompt,
 *  listing only the enabled specialists and how to invoke each. Regenerated per
 *  run so the instructions always match the live toggles. */
function teamBlock(enabled: SpecialistRole[], roles: RolesConfig): string {
  const rows = enabled.map(
    (r) => `- **${roles[r].label}** (${roleModelLabel(roles[r])}) — ${roles[r].blurb}\n  Invoke: \`maestro-role ${r}\``
  );
  return [
    '## Your specialist team',
    'You can delegate to the sub-agents below. Delegate the matching phase to each — do not do their work yourself.',
    'To invoke one, run this with the Bash/shell tool and pass the full task on stdin:',
    '',
    '```',
    "maestro-role <role> <<'TASK'",
    'Everything the specialist needs to know about this task, self-contained.',
    'TASK',
    '```',
    '',
    "It prints the specialist's final answer to stdout. Wait for it, then use the result. Each call is stateless, so",
    'include all needed context in the task. These runs can take several minutes — allow a generous command timeout',
    '(e.g. 600000 ms).',
    '',
    'Available specialists:',
    ...rows,
    '',
    'Coordinate them (a typical flow is plan → critique → build → verify), integrate their output, and own the final result.',
  ].join('\n');
}

/** The orchestrator's full system prompt: repo instructions + the orchestrator
 *  md + the generated team block. With no specialists enabled the caller passes
 *  the bare base instead (today's behavior). */
export function orchestratorPrompt(base: string | null, enabled: SpecialistRole[], roles: RolesConfig): string {
  const parts: string[] = [];
  if (base && base.trim()) parts.push(base.trim());
  if (roles.orchestrator.md.trim()) parts.push(roles.orchestrator.md.trim());
  if (enabled.length) parts.push(teamBlock(enabled, roles));
  return parts.join('\n\n');
}

