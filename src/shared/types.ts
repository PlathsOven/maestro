/** Full role config for the current settings: per-role, per-field fallback to
 *  DEFAULT_ROLES (or a blank def for a custom id) so partial saves never drop a
 *  field. Includes the orchestrator plus every current specialist id. */
export function resolveRoles(settings: Pick<GlobalSettings, 'roles' | 'specialists'>): RolesConfig {
  const out: RolesConfig = {};
  for (const id of [ORCHESTRATOR, ...specialistRoleIds(settings)]) {
    const base = DEFAULT_ROLES[id] ?? blankRoleDef(id);
    out[id] = { ...base, ...(settings.roles?.[id] ?? {}) };
  }
  return out;
}

