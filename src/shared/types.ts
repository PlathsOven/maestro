/**
 * Claude effort maps to an extended-thinking budget, which Haiku has no notion of
 * — so the effort control is meaningless there. Empty model = harness default,
 * which resolves to an effort-capable model.
 */
export function modelSupportsEffort(model: string): boolean {
  return !/haiku/i.test(model);
}

/**
 * The effort ladder to offer for a given model — the source of "effort levels
 * change per model". Codex carries its own per-model ladder (from its catalog,
 * on the ModelOption); Claude uses the canonical ladder minus Haiku; harnesses
 * whose adapter ignores effort (cursor/opencode/kimi/shell) expose none. An empty
 * result means: hide the effort control entirely.
 */
export function effortLevelsForModel(harness: HarnessId, model: string, opt?: ModelOption): EffortLevel[] {
  if (harness === 'codex') return opt?.efforts?.length ? opt.efforts : CODEX_EFFORT_LEVELS.slice(0, 4);
  if (harness === 'claude-code') return modelSupportsEffort(model) ? EFFORT_LEVELS : [];
  // Grok's reasoning models (grok-4.x) expose low…xhigh; grok-build-0.1 is a
  // non-reasoning model, so it shows no effort chip.
  if (harness === 'grok') return /grok-build/i.test(model) ? [] : GROK_EFFORT_LEVELS;
  return [];
}

/**
 * Resolve a stored effort id to a concrete level within `levels`, so a chip always
 * shows a valid entry from the model's own ladder — even after switching models
 * across harnesses (e.g. a Claude 'ultracode' left on a Codex model). Falls back
 * to the model's preferred default, then the app default, then the first level.
 * Returns null only when the model has no effort levels at all.
 */
export function resolveEffortLevel(
  stored: string | undefined,
  levels: EffortLevel[],
  preferred?: string
): EffortLevel | null {
  if (!levels.length) return null;
  return (
    levels.find((l) => l.id === stored) ??
    levels.find((l) => l.id === preferred) ??
    levels.find((l) => l.id === DEFAULT_EFFORT) ??
    levels[0]
  );
}

