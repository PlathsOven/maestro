/**
 * What kind of machine a host row describes. `'ssh'` is a box the user already
 * has; `'k8s'` is a workspace node Maestro manufactures on their cluster
 * (kubernetes-workspaces.md §3.1) and reaches through a supervised
 * `kubectl port-forward`. Past connect() the two are the same host.
 */
export type HostKind = 'ssh' | 'k8s';

/**
 * Cluster coordinates for a `kind: 'k8s'` host row. No credentials live here —
 * kubectl exercises the kubeconfig; Maestro only names the context.
 */
export interface K8sConfig {
  /** kubeconfig context name (from `kubectl config get-contexts`) */
  context: string;
  /** the namespace everything Maestro creates lives in (default "maestro") */
  namespace: string;
  /** workspace-node image; unset ⇒ the published default */
  image?: string;
  /** PVC size for /home/maestro (default "20Gi") */
  pvcSize?: string;
}

/** A context offered by the local kubeconfig, for the add-cluster picker. */
export interface K8sContext {
  name: string;
  cluster: string;
  /** the context's own default namespace, if it sets one */
  namespace: string;
  current: boolean;
}

/**
 * A saved SSH host. Projects on a host run every exec/spawn/pty/fs primitive on
 * that server (spec §6.6). v1 auth: SSH agent or an explicit key (passphrase
 * prompted, never stored) — no stored passwords. Host keys are TOFU-pinned on
 * first connect.
 */
export interface SshHostConfig {
  id: string;
  /** display name, defaults to host */
  label: string;
  /** hostname or a ~/.ssh/config alias */
  host: string;
  /** default 22 */
  port: number;
  user: string;
  /** v1: no stored passwords */
  auth: 'agent' | 'key';
  /** for auth: 'key' (passphrase prompted, never stored) */
  keyPath?: string;
  /** TOFU pin, set on first connect; a change is a hard warning */
  hostKeyFingerprint?: string;
  /** TOFU pins for ProxyJump hops (`host:port` → fingerprint), set on first use */
  jumpFingerprints?: Record<string, string>;
  /** A Maestro Cloud managed host (free beta, maestro-cloud-free-beta.md §3):
   *  provisioned by `/signup`, non-editable in host UIs, key generated by the app. */
  managed?: boolean;
  /** Port block `[portBase, portBase+99]` assigned by the shared box's signup so
   *  WORKSPACE_PORT allocation never collides across users on it (§3). */
  portBase?: number;
  /** Absent ⇒ 'ssh' (every row that existed before Kubernetes workspaces). */
  kind?: HostKind;
  /** Cluster config, iff kind === 'k8s'. `host`/`port` are then bookkeeping only:
   *  the real endpoint is whatever today's `kubectl port-forward` says
   *  (kubernetes-workspaces.md §3.1). */
  k8s?: K8sConfig;
}

