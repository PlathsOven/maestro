type MarkProps = { size?: number; className?: string; title?: string };

function Mark({ size = 14, className, title, children }: MarkProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      fillRule="evenodd"
      className={className ? `shrink-0 ${className}` : 'shrink-0'}
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
    >
      {children}
    </svg>
  );
}

/** The harness's own logo (Claude Code, Codex, Cursor, …); a terminal glyph for
 *  the plain shell or any id without a mark. Decorative unless `title` is set. */
export function HarnessLogo({ harness, size = 14, className, title }: MarkProps & { harness: HarnessId | string }) {
  const mark = HARNESS_MARKS[harness as HarnessId];
  if (!mark)
    return <SquareTerminal size={size} className={className ? `shrink-0 ${className}` : 'shrink-0'} aria-hidden />;
  return (
    <Mark size={size} className={className} title={title}>
      {mark}
    </Mark>
  );
}

